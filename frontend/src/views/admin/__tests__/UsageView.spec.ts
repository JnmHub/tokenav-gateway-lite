describe('admin UsageView reasoning effort column migration', () => {
  const mountView = () => mount(UsageView, {
    global: { stubs: {
      AppLayout: AppLayoutStub, UsageStatsCards: true, UsageFilters: UsageFiltersStub,
      UsageTable: UsageTableStub, UsageExportProgress: true, UsageCleanupDialog: true,
      UserBalanceHistoryModal: true, AuditLogModal: true, Pagination: true, Select: true,
      DateRangePicker: true, Icon: true, TokenUsageTrend: true,
      ModelDistributionChart: true, GroupDistributionChart: true, EndpointDistributionChart: true,
      OpsErrorLogTable: true, OpsErrorDetailModal: true,
    } },
  })

  const displayedColumns = (wrapper: ReturnType<typeof mount>) =>
    wrapper.get('[data-test="usage-table"]').attributes('data-columns').split(',')

  beforeEach(() => {
    vi.useFakeTimers()
    list.mockReset()
    getStats.mockReset()
    getSnapshotV2.mockReset()
    getModelStats.mockReset()
    listErrorLogs.mockReset()
    vi.mocked(localStorage.getItem).mockReset()
    vi.mocked(localStorage.setItem).mockReset()

    list.mockResolvedValue({ items: [], total: 0, pages: 0 })
    getStats.mockResolvedValue({
      total_requests: 0, total_input_tokens: 0, total_output_tokens: 0,
      total_cache_tokens: 0, total_tokens: 0, total_cost: 0, total_actual_cost: 0, average_duration_ms: 0,
    })
    getSnapshotV2.mockResolvedValue({ trend: [], models: [], groups: [] })
    getModelStats.mockResolvedValue({ models: [] })
    listErrorLogs.mockResolvedValue({ items: [], total: 0, pages: 0 })
  })

  afterEach(() => {
    vi.useRealTimers()
  })

  it('新浏览器默认显示实际思考档次', async () => {
    vi.mocked(localStorage.getItem).mockReturnValue(null)

    const wrapper = mountView()
    await flushPromises()

    expect(displayedColumns(wrapper)).toContain('reasoning_effort')
    expect(displayedColumns(wrapper)).not.toContain('user_agent')
  })

  it('首次打开新版时从旧隐藏配置中恢复实际思考档次', async () => {
    vi.mocked(localStorage.getItem).mockImplementation((key: string) => {
      if (key === 'usage-hidden-columns') return JSON.stringify(['reasoning_effort', 'user_agent'])
      return null
    })

    const wrapper = mountView()
    await flushPromises()

    expect(displayedColumns(wrapper)).toContain('reasoning_effort')
    expect(displayedColumns(wrapper)).not.toContain('user_agent')
    expect(localStorage.setItem).toHaveBeenCalledWith('usage-hidden-columns', JSON.stringify(['user_agent']))
    expect(localStorage.setItem).toHaveBeenCalledWith('usage-reasoning-effort-visible-v1', '1')
  })

  it('迁移完成后尊重管理员主动隐藏实际思考档次', async () => {
    vi.mocked(localStorage.getItem).mockImplementation((key: string) => {
      if (key === 'usage-hidden-columns') return JSON.stringify(['reasoning_effort', 'user_agent'])
      if (key === 'usage-reasoning-effort-visible-v1') return '1'
      return null
    })

    const wrapper = mountView()
    await flushPromises()

    expect(displayedColumns(wrapper)).not.toContain('reasoning_effort')
    expect(localStorage.setItem).not.toHaveBeenCalledWith('usage-reasoning-effort-visible-v1', '1')
  })
})
