// ProvideGrokOAuthHandler adds token-cache invalidation to manual Grok account
// refreshes while keeping the handler constructor easy to use in unit tests.
func ProvideGrokOAuthHandler(
	grokOAuthService *service.GrokOAuthService,
	adminService service.AdminService,
	quotaService *service.GrokQuotaService,
	tokenInvalidator service.TokenCacheInvalidator,
	reconciler *service.TokenRefreshService,
	auditService *service.OperationAuditService,
) *admin.GrokOAuthHandler {
	h := admin.NewGrokOAuthHandler(grokOAuthService, adminService, quotaService)
	h.SetTokenCacheInvalidator(tokenInvalidator)
	h.SetReconciler(reconciler)
	h.SetOperationAuditService(auditService)
	return h
}

